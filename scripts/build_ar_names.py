#!/usr/bin/env python3
"""**The Arabic name bank** — paper 115, 25 October 2026.

The owner keeps his own list of Arabic names and handed it over as a file:
`~/الأسماء العربية.txt`, which is a reading list and not a data format. It has a
title, a header that counts itself, rules of `═` and `─`, a section per letter,
and under each letter two headings — `الذكور:` and `الإناث:` — with one name to a
line. Between sections it also writes its own per-letter tallies, in brackets:
`(الذكور 50 — الإناث 68)`.

**What this script is for:** so that the owner's own file stays the source and
the CSV in `z_core/assets/` is only its reading — the same arrangement
`build_de_names.py` has, and the reason is the same: the day he adds a name, the
work is running this again rather than editing a generated file by hand.

**What it measured, and what the file says about itself.** Its header says 1292
male and 1135 female, 2427 in all. Parsed: **1292 + 1135 = 2427 lines, of which
2414 are distinct** — 13 names are in both lists, which is a fact about Arabic
names and not a mistake (أمل, نور, سلام and the like are given to either). The
owner said «about 2600»; the file says 2427 and the file is what ships. The 28
bracketed tallies are not names and are dropped by name here, because a count
line that became a dictionary entry would be the file reading its own furniture.

**Harakat are kept exactly as he wrote them.** 897 of the names carry a vowel
mark, and the mark is part of how he wrote it. The matching side folds them off
(`packs/ar.rs`), so a document written with marks and one written without both
find the name — and that fold is in the pack rather than here, so that this file
never loses a letter the owner typed. **No NFKC anywhere near this**: NFKC
decomposes the Arabic presentation forms into space + mark and cuts words in
two, which is measured in `z_core/src/text.rs`.

One name to a row, `given` for every one of them: the library is a list of given
names and holds no surnames, so the Arabic pack's family list is empty and says
so. 27 of the rows are two words — «ذو الفقار», «أمّ كُلثوم», «ست الملوك» — and
each one is **one** name, kept whole, because that is what it is.

Usage: `python3 scripts/build_ar_names.py [path to the owner's file]`
"""

import io
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / 'z_core' / 'assets' / 'ar_names_v1.csv'
DEFAULT = Path(os.path.expanduser('~')) / 'الأسماء العربية.txt'

# The file's own furniture, by name. A line that is one of these is not a name.
HEADINGS = ('الأسماء العربية',)
MALE, FEMALE = 'الذكور:', 'الإناث:'


def names_in(text: str) -> tuple[list[str], list[str]]:
    male: list[str] = []
    female: list[str] = []
    into: list[str] | None = None
    for raw in text.split('\n'):
        line = raw.strip()
        if not line:
            continue
        # Rules, the letter headings, the file's own counts, and its bracketed
        # per-letter tallies — furniture, each dropped by what it starts with.
        if line.startswith(('═', '─', 'الأحرف', 'عدد', 'المجموع', '(')):
            continue
        if line in HEADINGS:
            continue
        if line == MALE:
            into = male
            continue
        if line == FEMALE:
            into = female
            continue
        if into is None:
            # A name before any heading would be a name with no list; the file
            # has none, and if one ever appears it must be seen rather than
            # guessed at.
            raise SystemExit(f'a line before any heading: «{line}»')
        into.append(line)
    return male, female


def main() -> int:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    if not source.exists():
        print(f'the library is not at {source}', file=sys.stderr)
        return 1
    male, female = names_in(io.open(source, encoding='utf-8').read())
    both = set(male) & set(female)
    rows = []
    for name in male:
        rows.append((name, 'u' if name in both else 'm'))
    for name in female:
        if name in both:
            continue  # one row per name; the gender says it is given to either
        rows.append((name, 'f'))
    out = io.open(OUT, 'w', encoding='utf-8')
    out.write('# Arabic Given Names V1 — generated by scripts/build_ar_names.py\n')
    out.write('# A signal for Person detection, never a verdict: a dictionary hit\n')
    out.write('# can offer a name the rules would have walked past, and can never\n')
    out.write('# protect one by itself. See z_core/assets/licenses/arabic_names_sources.md\n')
    out.write(f'# Source: the owner\'s own library — {len(male)} male, {len(female)} female,\n')
    out.write(f'# {len(male) + len(female)} lines, {len(set(male) | set(female))} distinct.\n')
    out.write('# Harakat are kept as he wrote them; the fold is in packs/ar.rs.\n')
    out.write('name,type,gender,source,license,source_url,notes\n')
    for name, gender in rows:
        out.write(f"{name},given,{gender},the owner's own Arabic name library,"
                  f"the owner's own,-,one line of الأسماء العربية.txt\n")
    out.close()
    print(f'{OUT.relative_to(HERE)}: {len(rows)} rows · {len(male)} male · '
          f'{len(female)} female · {len(both)} in both lists')
    return 0


if __name__ == '__main__':
    sys.exit(main())
